/* Builds resume/applications/manifest.js — the list the editor's "Applying to"
   dropdown reads to switch between the master resume and every tailored
   application, live, with no page reload or network request.

   Each variant's full data object is embedded directly (not loaded via a
   <script src>), because the published Artifact is a single self-contained
   HTML page with no other files to fetch. Embedding is also what makes the
   switcher work identically whether the app is opened from resume/index.html
   or from the bundled artifact.js — same manifest, same mechanism either way.

   Run this after adding, renaming, or editing any resume in resume/ or
   resume/applications/, then re-run scripts/build-artifact.mjs to fold the
   refreshed manifest into the published page.

   Usage:  node scripts/build-manifest.mjs
*/

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const resumeDir = path.join(root, 'resume');
const appsDir = path.join(resumeDir, 'applications');
const outFile = path.join(appsDir, 'manifest.js');

/* Data files assign `window.RESUME = {...}` so they work standalone (opened
   directly, or copied over resume-data.js by the --data flag on
   render-resume-pdf.mjs). Pulling the object literal back out here, rather
   than requiring the files as modules, keeps that convention intact. */
function extractResumeObject(filePath) {
  var source = readFileSync(filePath, 'utf8');
  var match = source.match(/window\.RESUME\s*=\s*(\{[\s\S]*\});?\s*$/);
  if (!match) {
    throw new Error(filePath + ' does not end in a single `window.RESUME = {...}` assignment');
  }
  // eslint-disable-next-line no-new-func
  return new Function('return (' + match[1] + ')')();
}

function extractLabel(filePath, fallback) {
  var source = readFileSync(filePath, 'utf8');
  var match = source.match(/\/\/\s*LABEL:\s*(.+)/);
  return match ? match[1].trim() : fallback;
}

function slugify(name) {
  return name.replace(/-data\.js$/, '');
}

function titleCase(slug) {
  return slug.replace(/-/g, ' ').replace(/\b\w/g, function (c) { return c.toUpperCase(); });
}

var entries = [];

entries.push({
  slug: 'master',
  label: 'Master (all experience)',
  data: extractResumeObject(path.join(resumeDir, 'resume-data.js'))
});

var appFiles = readdirSync(appsDir)
  .filter(function (name) { return name.endsWith('-data.js'); })
  .sort();

appFiles.forEach(function (name) {
  var slug = slugify(name);
  var filePath = path.join(appsDir, name);
  entries.push({
    slug: slug,
    label: extractLabel(filePath, titleCase(slug)),
    data: extractResumeObject(filePath)
  });
});

var banner =
  '/* GENERATED by scripts/build-manifest.mjs — do not hand-edit.\n' +
  '   Regenerate after adding, renaming, or editing a resume:\n' +
  '     node scripts/build-manifest.mjs\n' +
  '*/\n\n';

writeFileSync(outFile, banner + 'window.RESUME_LIBRARY = ' + JSON.stringify(entries, null, 2) + ';\n');

console.log('Wrote ' + outFile + ' (' + entries.length + ' resume' + (entries.length === 1 ? '' : 's') + ')');
